// Regenerates docs/STATE.md from backlog + phase notes + decisions + activity.
// Idempotent. Never mutates any source of truth — only reads and writes STATE.md.
//
// Usage: node .claude/scripts/refresh-state.mjs

import { existsSync, readdirSync, renameSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { backlogItems, fmField, phaseDirs, readText, repoRoot, todayUtc } from '../hooks/lib.mjs';

const orNone = (lines) => (lines.length > 0 ? lines : ['_(none)_']);

function activeArcs(docsDir) {
    return phaseDirs(join(docsDir, 'phases')).flatMap((dir) => {
        const idx = join(dir, 'index.md');
        const st = fmField(idx, 'status');
        if (!st || st === 'done') return [];
        const rel = `${relative(docsDir, dir).replace(/\\/g, '/')}/`;
        return [`- [${fmField(idx, 'topic')}](${rel}) — phase: **${st}** — updated ${fmField(idx, 'updated')}`];
    });
}

function openByTag(items) {
    const byTag = new Map();
    for (const i of items.filter((i) => i.status === 'open')) {
        byTag.set(i.tag, [...(byTag.get(i.tag) ?? []), i.id]);
    }
    return [...byTag.keys()].sort().map((tag) => {
        const ids = byTag.get(tag);
        return `- **${tag}** (${ids.length}): ${ids.join(', ')}`;
    });
}

function recentDecisions(docsDir, n) {
    const dir = join(docsDir, 'decisions');
    if (!existsSync(dir)) return [];
    return readdirSync(dir)
        .filter((f) => /^\d+-.*\.md$/.test(f))
        .sort()
        .reverse()
        .slice(0, n)
        .map((f) => {
            const file = join(dir, f);
            const [id, title, st, date] = ['id', 'title', 'status', 'date'].map((k) => fmField(file, k));
            return `- ${date} — [${id}: ${title}](decisions/${f}) _(${st})_`;
        });
}

function recentActivity(docsDir, n) {
    const file = join(docsDir, 'activity.md');
    if (!existsSync(file)) return [];
    return readText(file)
        .split('\n')
        .filter((l) => /^- 2\d{3}-/.test(l))
        .slice(0, n);
}

export function refreshState() {
    const docsDir = join(repoRoot(), 'docs');
    const stateFile = join(docsDir, 'STATE.md');
    const items = backlogItems(join(docsDir, 'backlog.md'));
    const inProgress = items
        .filter((i) => i.status === 'in-progress')
        .map((i) => `- ${i.id} (${i.tag}) — ${i.slug}`);

    const lines = [
        '# Project state',
        '',
        `_Generated by \`/state refresh\` on ${todayUtc()}. Do not hand-edit — regenerate instead._`,
        '',
        '## Active arcs',
        '',
        ...orNone(activeArcs(docsDir)),
        '',
        '## In-progress backlog',
        '',
        ...orNone(inProgress),
        '',
        '## Open backlog by tag',
        '',
        ...orNone(openByTag(items)),
        '',
        '## Recent decisions (last 5)',
        '',
        ...orNone(recentDecisions(docsDir, 5)),
        '',
        '## Recent activity (last 5)',
        '',
        ...orNone(recentActivity(docsDir, 5)),
        '',
        '---',
        '_Sources: [backlog](backlog.md) · [decisions/](decisions/) · [phases/](phases/) · [activity](activity.md)_',
        '',
    ];

    const tmp = `${stateFile}.tmp`;
    writeFileSync(tmp, lines.join('\n'));
    renameSync(tmp, stateFile);
    return stateFile;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
    console.log(`Wrote ${refreshState()}`);
}
